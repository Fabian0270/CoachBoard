// Builds the phone page's encryption (D128) from @noble/ciphers into a string the
// server serves inline. Run after changing the @noble/ciphers version:
//   npm run build:phone-crypto -w server
// The output is committed, so building and testing the server need nothing extra;
// phoneCrypto.test.ts fails if it no longer matches what this script makes.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const here = path.dirname(fileURLToPath(import.meta.url))
const server = path.resolve(here, '..')
// npm workspaces hoist it to the root node_modules; a server-local copy wins if there is one.
const nobleDir = [path.join(server, 'node_modules/@noble/ciphers'), path.join(server, '../node_modules/@noble/ciphers')]
  .find((d) => fs.existsSync(d))
if (!nobleDir) throw new Error('@noble/ciphers is not installed')
const noble = JSON.parse(fs.readFileSync(path.join(nobleDir, 'package.json'), 'utf8'))
const license = fs.readFileSync(path.join(nobleDir, 'LICENSE'), 'utf8').trim()

export async function phoneCryptoSource() {
  const result = await build({
    stdin: {
      contents: `import { chacha20poly1305 } from '@noble/ciphers/chacha.js'
self.cbSeal = function (key, nonce, aad, data) { return chacha20poly1305(key, nonce, aad).encrypt(data) }`,
      resolveDir: server,
      loader: 'js',
    },
    bundle: true,
    format: 'iife',
    minify: true,
    target: ['safari14', 'chrome90'],
    legalComments: 'none',
    write: false,
  })
  const code = result.outputFiles[0].text.trim()
  return `// GENERATED by server/scripts/build-phone-crypto.mjs — do not edit.
// ChaCha20-Poly1305 from @noble/ciphers ${noble.version}, for the phone page (D128).
/*
${license}
*/
export const NOBLE_CIPHERS_VERSION = ${JSON.stringify(noble.version)}
export const PHONE_CRYPTO_LICENSE = ${JSON.stringify(license)}
/** Defines self.cbSeal(key, nonce, aad, plaintext) → ciphertext‖tag. */
export const PHONE_CRYPTO_JS = ${JSON.stringify(code)}
`
}

export const OUT = path.join(server, 'src/services/phoneCrypto.generated.ts')

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, await phoneCryptoSource())
  console.log('wrote', path.relative(process.cwd(), OUT))
}
